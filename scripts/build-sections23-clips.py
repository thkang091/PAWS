"""Build acquired Section 2/3 footage, leaving explicitly missing Levels unbound.

python scripts/build-sections23-clips.py --source PATH --ffmpeg PATH
Edits belong in training_sections23_content.py. Sources remain untouched.
"""
import argparse
import json
import subprocess
from pathlib import Path
from training_sections23_content import COURSES, CAPTIONS, MISSING, NOTES

ROOT = Path(__file__).resolve().parents[1]

def count_frames(ff, path, normalize=False):
    cmd = [ff, '-v', 'error', '-i', str(path)]
    if normalize:
        cmd += ['-vf', 'setpts=PTS-STARTPTS,fps=30', '-an']
    result = subprocess.run(cmd + ['-progress', 'pipe:1', '-f', 'null', '-'], capture_output=True, text=True, check=True)
    return [int(line.split('=')[1]) for line in result.stdout.splitlines() if line.startswith('frame=')][-1]

def build(source, ff, render_skills=None, content=None, prefix='sections23', asset_constant='SECTIONS23_ASSETS'):
    courses, captions, missing, notes = (COURSES, CAPTIONS, MISSING, NOTES) if content is None else (content.COURSES, content.CAPTIONS, content.MISSING, content.NOTES)
    inventory = json.loads((ROOT/f'scripts/training-{prefix}-sources.json').read_text(encoding='utf-8'))
    sources = {(entry['skill'], entry['id']): entry for entry in inventory}
    lessons, mapping, frames_by_source = {}, {}, {}
    lines = [f'// Generated by scripts/build-{prefix}-clips.py.', f'export const {asset_constant}: Record<string, Record<number, {{ source: number; poster: number }}>> = {{']
    for skill, (title, sequences) in courses.items():
        dest = ROOT / 'assets/training' / f'section-{skill}'
        dest.mkdir(parents=True, exist_ok=True)
        lessons[skill], mapping[skill] = [], []
        lines.append(f'  "{skill}": {{')
        exported = {}
        for level, sequence in enumerate(sequences, 1):
            if sequence is None:
                print(f'{skill} Level {level}: placeholder retained', flush=True)
                continue
            cmd = [ff, '-v', 'error', '-y']
            filters, steps, total = [], [], 0
            for index, ident in enumerate(sequence):
                entry = sources[skill, ident]
                path = ROOT / entry['projectFile'] if 'projectFile' in entry else source / entry['file']
                if (skill, ident) not in frames_by_source:
                    frames_by_source[skill, ident] = count_frames(ff, path, True)
                frames = frames_by_source[skill, ident]
                cmd += ['-i', str(path)]
                filters.append(f'[{index}:v]setpts=PTS-STARTPTS,fps=30,scale=1280:720:force_original_aspect_ratio=decrease,pad=1280:720:(ow-iw)/2:(oh-ih)/2,setsar=1,tpad=stop_mode=clone:stop_duration=0.1,trim=end_frame={frames},setpts=PTS-STARTPTS[v{index}]')
                step_title, cues = captions[skill][ident]
                assert all(0 <= at < frames/30 for at, text in cues), (skill, ident, frames)
                steps.append({'title': step_title, 'cues': [{'at': round(total/30+at, 6), 'text': text} for at, text in cues]})
                # The transition to another source must not imply one continuous attempt.
                if index and not steps[-1]['cues'][0]['text'].startswith(('Separate', 'Another')):
                    steps[-1]['cues'][0]['text'] = 'Another example: ' + steps[-1]['cues'][0]['text'][0].lower() + steps[-1]['cues'][0]['text'][1:]
                total += frames
            key = tuple(sequence)
            asset_level = exported.get(key, level)
            if key not in exported and (render_skills is None or skill in render_skills):
                filters.append(''.join(f'[v{i}]' for i in range(len(sequence))) + f'concat=n={len(sequence)}:v=1:a=0,fps=30,tpad=stop_mode=clone:stop_duration=0.1,trim=end_frame={total},settb=1/30,setpts=N[out]')
                output = dest / f'level-{level}.mp4'
                subprocess.run(cmd + ['-filter_complex', ';'.join(filters), '-map', '[out]', '-an', '-c:v', 'libx264', '-preset', 'veryfast', '-crf', '21', '-threads', '2', '-r', '30', '-fps_mode', 'cfr', '-frames:v', str(total), '-pix_fmt', 'yuv420p', '-movflags', '+faststart', str(output)], check=True)
                actual = count_frames(ff, output)
                assert actual == total, (skill, level, actual, total)
                subprocess.run([ff, '-v', 'error', '-y', '-ss', '0.5', '-i', str(output), '-frames:v', '1', '-q:v', '3', str(dest/f'level-{level}.jpg')], check=True)
            if key not in exported:
                assert (dest/f'level-{level}.mp4').exists(), (skill, level, 'Missing asset; render this skill')
                exported[key] = level
            lessons[skill].append({'id': f'section-{skill}-l{level}', 'levelNumber': level, 'duration': round(total/30, 6), 'coverageNote': notes[skill], 'steps': steps})
            mapping[skill].append({'levelNumber': level, 'sources': [sources[skill, ident]['file'] for ident in sequence], 'assetLevel': asset_level, 'frames': total})
            lines.append(f'    {level}: {{ source: require("../../../../assets/training/section-{skill}/level-{asset_level}.mp4"), poster: require("../../../../assets/training/section-{skill}/level-{asset_level}.jpg") }},')
            print(f'{skill} Level {level}: {total/30:.3f}s; {" + ".join(sequence)}', flush=True)
        lines.append('  },')
    lines.append('};')
    generated = ROOT/'src/features/train/media'
    (generated/f'{prefix}Lessons.generated.json').write_text(json.dumps(lessons, indent=2, ensure_ascii=False)+'\n', encoding='utf-8')
    (generated/f'{prefix}Assets.generated.ts').write_text('\n'.join(lines)+'\n', encoding='utf-8')
    (generated/f'{prefix}Coverage.generated.json').write_text(json.dumps({'missing': missing, 'courses': {skill: {'title': title, 'levels': mapping[skill]} for skill,(title,_) in courses.items()}}, indent=2)+'\n', encoding='utf-8')

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path, required=True)
    parser.add_argument('--ffmpeg', required=True)
    parser.add_argument('--render-skills', nargs='+', help='Render only these skills; keep existing assets for the rest')
    args = parser.parse_args()
    build(args.source, args.ffmpeg, args.render_skills)
