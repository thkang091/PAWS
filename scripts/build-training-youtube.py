"""Map Sections 2–6's existing lessons onto the same original YouTube intervals.

python scripts/build-training-youtube.py [--check] [--source PATH_TO_ACTUAL]
No downloads or video editing. --source additionally checks the acquired files'
SHA-256 hashes. Captions, lesson IDs, durations and progression remain untouched.
"""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MEDIA = ROOT / 'src/features/train/media'
PREFIXES = ('sections23', 'section4', 'section5', 'section6')


def read(path):
    return json.loads(path.read_text(encoding='utf-8-sig'))


def build(check=False, source=None):
    manifest = read(ROOT / 'scripts/training-youtube-sources.json')
    sources = manifest['sources']
    mappings = {}
    used = set()
    posters = ['// Generated by scripts/build-training-youtube.py. Artwork only; no MP4 imports.',
               'export const TRAINING_YOUTUBE_POSTERS: Record<string, Record<number, number>> = {']
    for prefix in PREFIXES:
        inventory = read(ROOT / f'scripts/training-{prefix}-sources.json')
        ids = {(item['skill'], item['file']): f"{item['skill']}/{item['id']}" for item in inventory}
        coverage = read(MEDIA / f'{prefix}Coverage.generated.json')
        lessons = read(MEDIA / f'{prefix}Lessons.generated.json')
        assert not coverage['missing'], f'{prefix}: unresolved media coverage'
        for skill, course in coverage['courses'].items():
            mappings[skill] = {}
            posters.append(f'  "{skill}": {{')
            for level in course['levels']:
                lesson = next(item for item in lessons[skill] if item['levelNumber'] == level['levelNumber'])
                assert len(lesson['steps']) == len(level['sources'])
                parts, cursor = [], 0
                for index, file in enumerate(level['sources']):
                    key = ids[skill, file]
                    entry = sources[key]
                    used.add(key)
                    assert entry['file'] == file, key
                    # Existing cue offsets are based on each input's 30fps export.
                    assert abs(lesson['steps'][index]['cues'][0]['at'] - cursor / 30) < .00001, key
                    remaining = entry['frames']
                    for part_index, (start, end) in enumerate(entry['ranges']):
                        frames = round((end - start) * 30) if part_index < len(entry['ranges']) - 1 else remaining
                        assert frames > 0 and abs(frames / 30 - (end - start)) < .034, key
                        parts.append(dict(videoId=entry['videoId'], channel=entry['channel'], title=entry['title'],
                                          startSeconds=start, endSeconds=end,
                                          clipStartSeconds=round(cursor / 30, 6),
                                          clipEndSeconds=round((cursor + frames) / 30, 6)))
                        cursor += frames
                        remaining -= frames
                    assert remaining == 0, key
                assert cursor == level['frames']
                assert abs(cursor / 30 - lesson['duration']) < .00001
                mappings[skill][str(level['levelNumber'])] = parts
                poster = f'assets/training/section-{skill}/level-{level["assetLevel"]}.jpg'
                assert (ROOT / poster).is_file(), poster
                posters.append(f'    {level["levelNumber"]}: require("../../../../{poster}"),')
            posters.append('  },')
    posters.append('};')
    assert used == set(sources), 'Unbound source entries'
    assert len(mappings) == 23 and sum(len(levels) for levels in mappings.values()) == 115
    if source:
        for key in used:
            entry = sources[key]
            path = ROOT / entry['file'] if entry['file'].startswith('assets/') else source / entry['file']
            assert hashlib.sha256(path.read_bytes()).hexdigest() == entry['sha256'], key
    outputs = {
        MEDIA / 'sections2to6YouTube.generated.json': json.dumps(mappings, ensure_ascii=False, indent=2) + '\n',
        MEDIA / 'trainingYouTubePosters.generated.ts': '\n'.join(posters) + '\n',
    }
    for path, contents in outputs.items():
        if check:
            assert path.read_text(encoding='utf-8') == contents, f'Stale generated file: {path.name}'
        else:
            path.write_text(contents, encoding='utf-8')
    print(f'{"Verified" if check else "Generated"} 23 lessons / 115 levels / {len(used)} acquired clips / '
          f'{len({sources[key]["videoId"] for key in used})} original videos.')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--source', type=Path)
    args = parser.parse_args()
    build(args.check, args.source)
